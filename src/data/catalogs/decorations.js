export const DEFAULT_FLOOR = 'floor_grass';

export function getDecoration(key) {
  const def = DECORATION_TYPES[key];
  if (!def || def.highlight) return def;
  const highlight = genericHighlight(def);
  return highlight ? { ...def, highlight } : def;
}

export function decoFamily(key) {
  const def = DECORATION_TYPES[key];
  if (!def) return null;
  if (def.kind === 'tree' || def.kind === 'bush' || def.bush || def.flower) return 'plant';
  if (def.gather && def.gather.mushroom) return 'plant';
  if (def.kind === 'rock' || def.kind === 'campfire') return 'object';
  if (def.shell || def.coral || def.rock) return 'object';
  if (def.kind === 'floor' || def.kind === 'path') return null;
  return 'object';
}

export function surfaceEntries() {
  const out = [];
  for (const [key, def] of Object.entries(DECORATION_TYPES)) {
    if (!def || def.kind !== 'floor' || !def.surface || !def.surface.texture) continue;
    out.push({ ...def.surface, key, label: def.surface.label || def.displayName || key });
  }
  return out;
}

export function decoRadius(def) {
  if (def.blocks === false) return 0;
  return def.radius || 0;
}

export function decoHeight(def) {
  if (def.blocks === false) return 0;
  return def.height || 0;
}

function genericHighlight(def) {
  if (def.kind === 'tree') return { ringColor: [0.55, 0.95, 0.5], ringSize: ringFor(def.radius, 0.9) };
  if (def.kind === 'rock') return { ringColor: [0.8, 0.82, 0.9], ringSize: ringFor(def.radius, 0.8) };
  return null;
}

function ringFor(radius, fallback) {
  return Math.round(Math.max(1.2, (radius || fallback) * 2.2) * 100) / 100;
}